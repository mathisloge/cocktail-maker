#!/usr/bin/env python3
"""Generate the docs colour files from the kiosk's `gui/ui/theme/colors.slint`.

Writes `docs/ui/supplemental/css/palette.css` and `docs/system/modules/ROOT/partials/d2-style.d2`.
With `--check`, it writes nothing and exits 1 when a file differs from what it would generate.
"""

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SLINT = REPO / "gui/ui/theme/colors.slint"
CSS = REPO / "docs/ui/supplemental/css/palette.css"
D2 = REPO / "docs/system/modules/ROOT/partials/d2-style.d2"

SOURCE = "gui/ui/theme/colors.slint"
GENERATOR = "tools/palette/generate_palette.py"
HEADER = f"Generated by {GENERATOR} from {SOURCE}. Do not edit by hand."


def read_primitives(slint_text: str) -> dict[str, str]:
    """The `name -> #rrggbb` pairs of `global Primitives { ... }`, in file order, lowercased."""
    block = re.search(r"\bglobal\s+Primitives\s*\{(.*?)\n\}", slint_text, re.DOTALL)
    if block is None:
        raise ValueError("colors.slint has no `global Primitives` block")
    body = re.sub(r"/\*.*?\*/", "", block.group(1), flags=re.DOTALL)
    body = re.sub(r"//[^\n]*", "", body)
    pairs = re.findall(r"property\s*<color>\s*([\w-]+)\s*:\s*(#[0-9a-fA-F]{6})\s*;", body)
    return {name: value.lower() for name, value in pairs}


def mix(a: str, b: str, weight_a: float) -> str:
    """Mix two #rrggbb colours per channel, `weight_a` of `a`, rounding half up."""
    out = "#"
    for i in (1, 3, 5):
        channel = int(a[i : i + 2], 16) * weight_a + int(b[i : i + 2], 16) * (1 - weight_a)
        out += f"{int(channel + 0.5):02x}"
    return out


def derived(colors: dict[str, str]) -> dict[str, str]:
    return {
        "sand-muted": mix(colors["sand"], colors["ink"], 0.6),
        "sand-soft": mix(colors["sand"], colors["ink"], 0.8),
    }


def render_css(colors: dict[str, str]) -> str:
    lines = [f"/* {HEADER} */", "", ":root {"]
    lines += [f"  --cm-{name}: {value};" for name, value in {**colors, **derived(colors)}.items()]
    lines += ["}", ""]
    return "\n".join(lines)


# The edge kinds of the diagrams: the primitive each one draws in and its dash, 0 for a solid line.
# The meanings are fixed site-wide. The dash is a second cue, so colour is never the only one.
EDGE_KINDS = {
    "power": ("orange-red", 0),
    "data": ("slate-light", 4),
    "fluid": ("green", 0),
    "mechanical": ("violet", 2),
    "interaction": ("amber-light", 0),
    "fault": ("pink", 0),
}


# The part classes of the boxes: the look of `block` with the outline in the colour of an edge kind.
PART_KINDS = ("power", "data", "fluid", "mechanical", "interaction")


def render_d2(colors: dict[str, str]) -> str:
    c = {**colors, **derived(colors)}
    parts = "\n".join(
        f"""  {kind}-part: {{
    style: {{
      fill: "{c["ink-elevated"]}"
      stroke: "{c[EDGE_KINDS[kind][0]]}"
      font-color: "{c["cream"]}"
      border-radius: 4
    }}
  }}"""
        for kind in PART_KINDS
    )
    edge_kinds = "\n".join(
        f"""  {kind}: {{
    style: {{
      stroke: "{c[primitive]}"
      stroke-width: 2
{f"      stroke-dash: {dash}\n" if dash else ""}      font-color: "{c[primitive]}"
    }}
  }}"""
        for kind, (primitive, dash) in EDGE_KINDS.items()
    )
    return f"""# {HEADER}
vars: {{
  d2-config: {{
    layout-engine: tala
  }}
}}
style.fill: "{c["ink"]}"
classes: {{
  block: {{
    style: {{
      fill: "{c["ink-elevated"]}"
      stroke: "{c["amber"]}"
      font-color: "{c["cream"]}"
      border-radius: 4
    }}
  }}
{parts}
  actor: {{
    shape: person
    width: 64
    height: 80
    style: {{
      fill: "{c["ink-elevated"]}"
      stroke: "{c["amber-light"]}"
      font-color: "{c["cream"]}"
    }}
  }}
  external: {{
    style: {{
      fill: "{c["ink"]}"
      stroke: "{c["sand"]}"
      stroke-dash: 4
      font-color: "{c["sand"]}"
    }}
  }}
  boundary: {{
    style: {{
      fill: "{c["ink-raised"]}"
      stroke: "{c["amber"]}"
      stroke-width: 2
      bold: true
      font-color: "{c["amber-light"]}"
    }}
  }}
  normal: {{
    style: {{
      stroke: "{c["sand-muted"]}"
      stroke-width: 1
      font-color: "{c["sand-soft"]}"
    }}
  }}
{edge_kinds}
  key: {{
    style: {{
      stroke-width: 3
      bold: true
    }}
  }}
}}
"""


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 if a generated file is stale")
    parser.add_argument("--slint", type=Path, default=SLINT)
    parser.add_argument("--css", type=Path, default=CSS)
    parser.add_argument("--d2", type=Path, default=D2)
    args = parser.parse_args(argv)

    colors = read_primitives(args.slint.read_text(encoding="utf-8"))
    outputs = {args.css: render_css(colors), args.d2: render_d2(colors)}
    if args.check:
        stale = [p for p, text in outputs.items() if not p.is_file() or p.read_text(encoding="utf-8") != text]
        for path in stale:
            print(f"{path} is stale, run {GENERATOR}", file=sys.stderr)
        return 1 if stale else 0
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
